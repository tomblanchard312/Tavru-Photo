#!/usr/bin/env python3
"""Export pinned Eridu Phosphor outlines as SVGs. Requires fonttools 4.60.1."""
import argparse
import json
import re
import shutil
import subprocess
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen

REVISION = 'd3b4cdc03706ac100fae2de907282575652b76ad'
parser = argparse.ArgumentParser()
parser.add_argument('eridu_style', type=Path)
args = parser.parse_args()
source = args.eridu_style.resolve()
if subprocess.check_output(['git', '-C', str(source), 'rev-parse', 'HEAD'], text=True).strip() != REVISION:
    raise SystemExit('Use the pinned eridu-style revision ' + REVISION)
root = Path(__file__).resolve().parents[1]
mapping = json.loads((root / 'assets/icons/eridu-map.json').read_text())
glyph_source = (source / 'src/icons.rs').read_text().split('pub mod duotone')[0]
points = dict(re.findall(r'pub const (\w+): &str = "\\u\{([0-9a-f]+)\}";', glyph_source))
lines = ['//! Generated by scripts/import-eridu-icons.py; see assets/icons/eridu-map.json and ATTRIBUTION.md.', '']
for style in ['regular', 'fill']:
    dest = root / 'assets/icons/eridu' / style
    dest.mkdir(parents=True, exist_ok=True)
    font = TTFont(source / 'fonts/phosphor' / f'Phosphor-{style.title()}.ttf')
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    for name in sorted(set(mapping.values())):
        glyph = cmap[int(points[name], 16)]
        pen = SVGPathPen(glyphs)
        glyphs[glyph].draw(pen)
        svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" fill="currentColor"><path transform="translate(0 960) scale(1 -1)" d="{pen.getCommands()}"/></svg>\n'
        (dest / f'{name.lower()}.svg').write_text(svg)
    ellipse = (dest / 'circle_dashed.svg').read_text().replace('<path ', '<g transform="translate(0 154) scale(1 .7)"><path ').replace('</svg>', '</g></svg>')
    (dest / 'ellipse_dashed.svg').write_text(ellipse)
    lines.append(f'pub static {"ICONS" if style == "regular" else "FILLED_ICONS"}: &[(&str, &[u8])] = &[')
    for alias, name in mapping.items():
        chosen = 'fill' if alias == 'star-filled' else style
        name = 'ELLIPSE_DASHED' if alias == 'ellipse-dashed' else name
        lines.append(f'    ("{alias}", include_bytes!("../../../assets/icons/eridu/{chosen}/{name.lower()}.svg")),')
    lines.extend(['];', ''])
shutil.copyfile(source / 'fonts/phosphor/LICENSE', root / 'assets/icons/eridu/LICENSE')
(root / 'crates/ui-egui/src/icon_data.rs').write_text('\n'.join(lines))
